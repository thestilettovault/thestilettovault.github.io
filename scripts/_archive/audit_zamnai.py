# -*- coding: utf-8 -*-
"""
Audit Zamnai Board -- TheGothicVault
Reads the user's production 'zamnai' board, checks each pin for affiliate coverage.
OK  = has affiliate program
NO  = no affiliate -> delete

Usage:
    python audit_zamnai.py          -> report only
    python audit_zamnai.py delete   -> try auto-delete non-affiliate pins
"""

import sys
import os
import requests
sys.path.insert(0, os.path.dirname(__file__))
sys.stdout.reconfigure(encoding='utf-8')

from gothic_scout import check_affiliate

PROD_TOKEN      = "pina_REDACTED"
SANDBOX_TOKEN   = "pina_REDACTED"
ZAMNAI_BOARD_ID = "522347325470861868"
PROD_API        = "https://api.pinterest.com/v5"

# Load write token from .env if available (generated by get_write_token.py)
def _load_write_token():
    env_path = os.path.join(os.path.dirname(__file__), ".env")
    if os.path.exists(env_path):
        with open(env_path, "r") as f:
            for line in f:
                if line.startswith("PINTEREST_WRITE_TOKEN="):
                    return line.strip().split("=", 1)[1]
    return SANDBOX_TOKEN  # fallback

WRITE_TOKEN = _load_write_token()


def get_zamnai_pins():
    pins = []
    bookmark = None
    headers = {"Authorization": f"Bearer {PROD_TOKEN}"}
    while True:
        params = {"page_size": 25}
        if bookmark:
            params["bookmark"] = bookmark
        r = requests.get(
            f"{PROD_API}/boards/{ZAMNAI_BOARD_ID}/pins",
            headers=headers, params=params, timeout=15
        )
        if not r.ok:
            print(f"  ERROR {r.status_code}: {r.text[:200]}")
            break
        data = r.json()
        pins.extend(data.get("items", []))
        bookmark = data.get("bookmark")
        if not bookmark:
            break
    return pins


def delete_pin_prod(pin_id):
    headers = {"Authorization": f"Bearer {WRITE_TOKEN}"}
    r = requests.delete(f"{PROD_API}/pins/{pin_id}", headers=headers, timeout=10)
    if r.status_code not in (200, 204):
        print(f"      HTTP {r.status_code}: {r.text[:120]}")
    return r.status_code in (200, 204)


def audit():
    print("\n" + "="*60)
    print("TheGothicVault -- Audit: Zamnai Board")
    print("="*60)

    pins = get_zamnai_pins()
    print(f"\nFound {len(pins)} pins\n")

    if not pins:
        print("Board is empty or API error.")
        return [], []

    ok_pins     = []
    no_aff_pins = []

    for pin in pins:
        pin_id = pin.get("id", "")
        title  = pin.get("title", "") or ""
        link   = pin.get("link", "") or ""
        url    = link or title or ""

        aff = check_affiliate(url)

        if aff:
            ok_pins.append(pin)
            badge = f"[OK]  {aff['commission']} ({aff['program']})"
        else:
            no_aff_pins.append(pin)
            badge = "[NO]  NO AFFILIATE"

        name = (title or url)[:55]
        print(f"  {badge}")
        print(f"       {name}")
        print(f"       {url[:70]}")
        print(f"       PIN ID: {pin_id}")
        print()

    print("-"*60)
    print(f"  [OK]: {len(ok_pins)}")
    print(f"  [NO]: {len(no_aff_pins)}  <- delete these")
    print("-"*60)

    if no_aff_pins:
        print("\nPins to delete manually in Pinterest:")
        for p in no_aff_pins:
            label = (p.get("title") or p.get("link") or "")[:60]
            print(f"  DEL  {p['id']}  |  {label}")

    return ok_pins, no_aff_pins


def auto_delete(no_aff_pins):
    if not no_aff_pins:
        print("\nNothing to delete.")
        return

    print(f"\nAttempting to delete {len(no_aff_pins)} pins...")
    deleted = 0
    failed  = 0

    for pin in no_aff_pins:
        pin_id = pin.get("id")
        if delete_pin_prod(pin_id):
            label = (pin.get("title") or pin.get("link") or "")[:50]
            print(f"  DELETED: {label}")
            deleted += 1
        else:
            print(f"  FAILED : pin {pin_id}  (likely no write permission on production board)")
            failed += 1

    print(f"\nDeleted: {deleted} | Failed: {failed}")
    if failed:
        print("  -> Delete failed ones manually in Pinterest using IDs above")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "report"
    ok_pins, no_aff_pins = audit()

    if cmd == "delete" and no_aff_pins:
        print("\nStarting auto-delete...")
        auto_delete(no_aff_pins)
    elif no_aff_pins:
        print(f"\nRun with 'delete' to attempt auto-delete:")
        print("  python audit_zamnai.py delete")
